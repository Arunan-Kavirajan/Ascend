const pagesDir = path.join(process.cwd(), 'src/pages');
const files = fs.readdirSync(pagesDir).filter(f => f.endsWith('.tsx'));

for (const file of files) {
  const filePath = path.join(pagesDir, file);
  let content = fs.readFileSync(filePath, 'utf8');
  
  if (content.includes('react-icons/fi')) {
    // Remove the import statement
    content = content.replace(/import\s+\{[^}]+\}\s+from\s+["']react-icons\/fi["'];?\r?\n?/g, '');
    
    // Replace icon components
    for (const [icon, svg] of Object.entries(iconMap)) {
      // Handle <FiIcon /> and <FiIcon ...props />
      const selfClosingRegex = new RegExp(`<${icon}\\b([^>]*)/>`, 'g');
      content = content.replace(selfClosingRegex, (match, propsGroup) => {
        let newSvg = svg;
        let props = propsGroup || '';
        
        const sizeMatch = props.match(/size={?(\d+)}?/);
        if (sizeMatch) {
            newSvg = newSvg.replace('width="1em" height="1em"', `width="${sizeMatch[1]}" height="${sizeMatch[1]}"`);
            props = props.replace(sizeMatch[0], '');
        }
        
        const colorMatch = props.match(/color=["']([^"']+)["']/);
        if (colorMatch) {
            newSvg = newSvg.replace(/stroke="currentColor"/g, `stroke="${colorMatch[1]}"`);
            newSvg = newSvg.replace(/fill="currentColor"/g, `fill="${colorMatch[1]}"`);
            props = props.replace(colorMatch[0], '');
        }
        
        props = props.trim();
        if (props) {
            newSvg = newSvg.replace('<svg ', `<svg ${props} `);
        }
        return newSvg;
      });
      
      // Handle mode.icon reference in arrays
      const iconRefRegex = new RegExp(`\\b${icon}\\b`, 'g');
      content = content.replace(iconRefRegex, `((props) => { let svg = \`${svg}\`; if(props.size) svg = svg.replace('width="1em" height="1em"', 'width="'+props.size+'" height="'+props.size+'"'); if(props.className) svg = svg.replace('<svg ', '<svg className="'+props.className+'" '); if(props.style) svg = svg.replace('<svg ', '<svg style={'+JSON.stringify(props.style)+'} '); return <span dangerouslySetInnerHTML={{__html: svg}} />; })`);
    }
    
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`Updated ${file}`);
  }
}
